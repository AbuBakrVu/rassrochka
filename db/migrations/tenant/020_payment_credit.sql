-- Частичная оплата и переплата (lib/payments.ts).
--
-- credit — сколько клиент уже внёс в счёт следующего, ещё не закрытого
-- взноса. Раньше остаток меньше полного взноса приписывался к последнему
-- закрытому взносу и долг не уменьшал: деньги в кассе были, а в графике —
-- нет. Старые такие переплаты этой миграцией не пересчитываются — найти
-- их можно запросом из OPERATIONS.md («Переплаты до миграции 020»).

alter table deals add column credit numeric(12,2) not null default 0
  check (credit >= 0);
